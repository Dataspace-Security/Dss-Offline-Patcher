// Markdown renders the report with the template's structure and headings
// (sections 1–9; section 10 of the template is product requirements and is
// not part of a generated report).

func cell(s string) string {
	s = strings.TrimSpace(s)
	if s == "" {
		return "—"
	}
	s = strings.ReplaceAll(s, "\r", "")
	s = strings.ReplaceAll(s, "\n", "<br>")
	return strings.ReplaceAll(s, "|", `\|`)
}

func cp(c CountPct) string { return fmt.Sprintf("%d / %.1f %%", c.Count, c.Pct) }

// Markdown returns report.md.
func (pk *Pack) Markdown() string {
	var b strings.Builder
	w := func(format string, a ...any) { fmt.Fprintf(&b, format, a...) }
	m, prof := pk.Meta, pk.Profile

	w("# Patch Management Compliance Report\n\n")
	w("**Report type:** %s  \n", m.ReportType)
	w("**Control domain:** %s  \n", m.ControlDomain)
	w("**Coverage model:** %s  \n", m.CoverageModel)
	w("**Document status:** %s  \n", m.DocumentStatus)
	w("**Regulatory review date:** %s  \n", m.RegulatoryReviewDate)
	w("**Prepared for:** %s  \n", cell(m.PreparedFor))
	w("**Reporting period:** %s to %s  \n", m.Period.From, m.Period.To)
	w("**Report ID:** `%s`  \n", m.ReportID)
	w("**Generated at:** %s  \n", m.GeneratedAt)
	w("**Generated by:** %s / %s  \n\n", cell(m.GeneratedBy.User), m.GeneratedBy.Role)
	w("> **Important:** %s\n\n", Disclaimer)
	if m.Redacted {
		w("> **Redacted copy:** hostnames, endpoint IDs, IP addresses and user IDs are stable pseudonyms.\n\n")
	}
	w("---\n\n")

	// §1
	es := pk.ExecutiveSummary
	w("## 1. Executive summary\n\n| Measure | Result |\n|---|---:|\n")
	w("| In-scope endpoints | %d |\n", es.InScopeEndpoints)
	w("| Endpoints with current inventory | %s |\n", cp(es.CurrentInventory))
	w("| Endpoints compliant with applicable patch policy | %s |\n", cp(es.CompliantWithPolicy))
	w("| Endpoints overdue for one or more required patches | %s |\n", cp(es.Overdue))
	w("| Endpoints with stale inventory | %s |\n", cp(es.StaleInventory))
	w("| Endpoints pending restart | %d |\n", es.PendingRestart)
	w("| Approved patch exceptions still active | %d |\n", es.ActiveExceptions)
	w("| Emergency patches open past target | %d |\n", es.EmergencyOpenPastTarget)
	w("| Control findings: critical / high / medium / low | %d / %d / %d / %d |\n", es.FindingsBySeverity["critical"], es.FindingsBySeverity["high"], es.FindingsBySeverity["medium"], es.FindingsBySeverity["low"])
	w("| Evidence completeness | %.0f %% |\n\n", es.EvidenceCompletenessPct)
	oa := pk.OverallAssessment
	w("### Overall assessment\n\n**%s**", oa.Status)
	if oa.Source == "profile" {
		w(" (reviewer's conclusion; computed suggestion: %s)", oa.Suggested)
	} else {
		w(" (computed suggestion; the reviewer may set the conclusion in the report profile)")
	}
	w("\n\n**Assessment rationale:** %s\n\n### Key findings\n\n", oa.Rationale)
	if len(pk.KeyFindings) == 0 {
		w("No findings.\n\n")
	}
	for i, f := range pk.KeyFindings {
		w("%d. **%s** (%s, %s) — %s Impact: %s Affected: %d. Owner: %s. Due: %s.\n", i+1, f.Title, f.ID, f.Severity, f.Observation, f.Risk, f.AffectedCount, f.Owner, f.DueDate)
	}
	w("\n---\n\n")

	// §2
	w("## 2. Scope and methodology\n\n### 2.1 Organization and regulatory profile\n\n| Attribute | Value |\n|---|---|\n")
	w("| Legal entity | %s |\n", cell(prof.LegalEntity))
	w("| Business / regulated activity | %s |\n", cell(prof.RegulatedActivity))
	w("| Applicable regulator(s) | %s |\n", cell(strings.Join(prof.Regulators, ", ")))
	w("| Entity category / size category where relevant | %s |\n", cell(prof.EntityCategory))
	w("| Assessment owner | %s |\n", cell(prof.AssessmentOwner))
	w("| Independent reviewer | %s |\n", cell(prof.IndependentReviewer))
	sys := prof.SystemsInScope
	if len(pk.Scope.Sites) > 0 {
		sys = strings.TrimSpace(sys + " (enrolled sites: " + strings.Join(pk.Scope.Sites, ", ") + ")")
	}
	w("| Systems in scope | %s |\n", cell(sys))
	w("| Endpoint types in scope | %s |\n", cell(prof.EndpointTypes))
	w("| Operating systems / application families | %s |\n", cell(strings.Join(pk.Scope.OSFamilies, "; ")+"; applications: "+strings.Join(pk.Scope.ApplicationVendors, ", ")))
	var ex []string
	for _, x := range prof.Exclusions {
		ex = append(ex, fmt.Sprintf("%s — %s; approved by %s; review %s", x.System, x.Reason, orDash(x.ApprovedBy), orDash(x.ReviewDate)))
	}
	if pk.Scope.RetiredExcluded > 0 {
		ex = append(ex, fmt.Sprintf("%d retired endpoints (decommissioned in %s)", pk.Scope.RetiredExcluded, Product))
	}
	w("| Exclusions | %s |\n\n", cell(strings.Join(ex, "<br>")))
	om := prof.OfflineModel
	w("### 2.2 Offline update-delivery model\n\nDescribe how the organization acquires and distributes updates without endpoints connecting to the internet.\n\n")
	w("- **Connected acquisition zone:** %s\n", cell(om.AcquisitionZone))
	w("- **Transfer boundary:** %s\n", cell(om.TransferBoundary))
	w("- **Quarantine and verification:** %s\n", cell(om.Quarantine))
	w("- **Internal patch service/repository:** %s\n", cell(om.Repository))
	w("- **Endpoint communications:** %s\n", cell(om.EndpointComms))
	w("- **Network egress enforcement evidence:** %s\n\n", cell(om.EgressEvidence))
	w("### 2.3 Assessment method\n\nFor each control, the report should record:\n\n")
	w("1. Whether the source applies to this entity and system scope.\n2. The control requirement or the organization’s policy implementing it.\n3. The test performed and period sampled.\n4. Evidence references, collection time, and integrity/hash where available.\n5. Result and rationale.\n6. Finding severity, owner, corrective action, and due date if not met.\n\n")
	w("In this report every in-scope endpoint and every applicable endpoint/update pair of the period %s to %s is tested (population, not a sample); the state is evaluated at %s.\n\n", m.Period.From, m.Period.To, m.Period.AsOf)
	w("### 2.4 Status values\n\n")
	w("- **Compliant:** Evidence demonstrates the control operated as required for the tested scope and period.\n")
	w("- **Partially compliant:** Control exists but coverage, timeliness, evidence, or execution has gaps.\n")
	w("- **Non-compliant:** Required control is absent or failed materially.\n")
	w("- **Not applicable:** Documented rationale shows the requirement does not apply to this entity or system.\n")
	w("- **Not assessed:** Evidence or testing is insufficient to conclude.\n\n")
	w("Do not treat missing endpoint telemetry as compliant. Classify it as stale, offline, or not assessed until independently resolved.\n\n---\n\n")

	// §3
	w("## 3. Common patch management control matrix\n\nThe following baseline is designed to support audit work across sectors. It is a product control framework, not a claim that every row is explicitly mandated in identical wording by every Indian regulator.\n\n")
	w("| Control ID | Control objective | Auditor evidence / product data | Suggested test | Status |\n|---|---|---|---|---|\n")
	for _, c := range pk.Controls {
		ev := c.AuditorEvidence + "<br>**Product data:** " + c.Evidence + " (" + strings.Join(c.EvidenceIDs, ", ") + ")"
		test := c.SuggestedTest + "<br>**Performed:** " + c.TestPerformed
		st := "**" + c.Status + "** (" + c.Source + ")<br>" + c.Rationale
		if c.Manual != nil && c.Source != "manual" && (c.Manual.Note != "" || c.Manual.EvidenceRef != "") {
			st += "<br>Reviewer note: " + orDash(c.Manual.Note) + "; evidence: " + orDash(c.Manual.EvidenceRef)
		}
		w("| %s | %s | %s | %s | %s |\n", c.ID, cell(c.Objective), cell(ev), cell(test), cell(st))
	}
	w("\n---\n\n")

	// §4
	w("## 4. India regulatory mapping\n\n### Applicability note\n\nRegulations apply to the regulated entity, not automatically to every customer of a patch-management product. Configure this section from the entity’s legal/regulatory profile. Product-generated mappings should be treated as **candidate mappings** until reviewed against the current instrument, amendments, entity category, and supervisory directions.\n\n")
	w("| Framework / source | Potential patch-related expectation | Evidence the report can provide | Applicability / auditor conclusion |\n|---|---|---|---|\n")
	for _, r := range pk.RegulatoryMappings {
		name := r.Framework + " — " + r.Instrument
		if r.Instrument == "" || strings.HasPrefix(r.Instrument, r.Framework) {
			name = r.Instrument
			if name == "" {
				name = r.Framework
			}
		}
		evid := r.Evidence
		if evid == "" {
			evid = "Map exact instrument and evidence."
		}
		concl := r.Conclusion
		if r.Notes != "" {
			concl += "<br>Notes: " + r.Notes
		}
		w("| **%s** | %s | %s | %s |\n", cell(name), cell(r.Expectation), cell(evid), cell(concl))
	}
	w("\n### 4.1 Regulatory mapping fields required in the product\n\nEach mapped obligation should be stored as a versioned record with:\n\n")
	w("- Regulator and framework name.\n- Circular/direction title, identifier, publication date, effective date, amendment/version, and official source URL.\n- Exact section/paragraph/control reference, captured for review and not paraphrase alone.\n- Entity categories and system scopes to which the obligation applies.\n- Applicability rationale and reviewer/approval date.\n- Mapped product controls and evidence fields.\n- Assessment result, findings, owner, corrective action, due date, and evidence references.\n- Last legal/compliance review date and next review trigger/date.\n\n")
	w("The product should support custom frameworks and customer control mappings; it should not label an organization “RBI compliant” or “SEBI compliant” based solely on patch status.\n\n")
	w("Mappings in this report come from report profile version %d (%s).\n\n---\n\n", pk.ProfileVersion.Version, map[bool]string{true: "defaults: nothing saved yet", false: "saved " + pk.ProfileVersion.EditedAt + " by " + pk.ProfileVersion.EditedBy}[pk.ProfileVersion.IsDefault])

	// §5
	w("## 5. Patch timeliness and compliance calculation\n\n### 5.1 Policy-defined deadlines\n\nDeadlines must be configurable by entity policy and applicable regulation. Do not hard-code one universal timeline across all customers or systems.\n\n")
	w("| Priority / classification | Organization-defined maximum time | Source / policy | Clock start definition | Allowed exception process |\n|---|---:|---|---|---|\n")
	byP := map[string]PriorityStats{}
	for _, s := range pk.Timeliness.ByPriority {
		byP[s.Priority] = s
	}
	row := func(label string, prs ...string) {
		var days, src, clk, exc []string
		for _, p := range prs {
			s := byP[p]
			pre := ""
			if len(prs) > 1 {
				pre = p + ": "
			}
			days = append(days, fmt.Sprintf("%s%d days", pre, s.MaxDays))
			src = append(src, pre+s.Source)
			clk = append(clk, pre+clockLabel(s.ClockStart))
			exc = append(exc, pre+s.ExceptionProcess)
		}
		w("| %s | %s | %s | %s | %s |\n", label, cell(strings.Join(days, "<br>")), cell(strings.Join(dedupe(src), "<br>")), cell(strings.Join(dedupe(clk), "<br>")), cell(strings.Join(dedupe(exc), "<br>")))
	}
	row("Emergency / actively exploited", "emergency")
	row("High / critical", "critical", "high")
	row("Moderate", "moderate")
	row("Low", "low")
	w("\n**Important SEBI note:** The 2024 CSCRF source contains maximum timelines for high, moderate, and low criticality patches and separate treatment for emergency patching. The applicable entity category, exact implementation requirements, and amendments/FAQs must be confirmed. Where a binding deadline applies, the stricter applicable obligation should be reflected in the customer’s configured policy after compliance review.\n\n")
	w("### 5.2 Calculation rules\n\nFor each applicable endpoint/update pair, retain:\n\n")
	w("- Patch release/availability date and the date the organization became aware of the patch.\n- Date the update was acquired and made available internally.\n- Applicability result and rationale.\n- Required deadline and source of that deadline.\n- Installation and verification timestamps.\n- Current outcome: compliant, overdue, pending, failed, offline, not applicable, or approved exception.\n\n")
	w("**Compliant on time** means the applicable update (or approved superseding update) was installed and verified by the configured deadline. An approved exception is reported separately and must not be counted as patched.\n\n")
	tl := pk.Timeliness
	w("Results at %s (%d endpoint/update pairs; every pair is listed in evidence E-007):\n\n", tl.AsOf, tl.PairsTotal)
	w("| Priority | Pairs | Compliant on time | Verified late | Overdue | Pending | Failed | Offline / stale | Exception | Not applicable | On time |\n|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|\n")
	for _, s := range tl.ByPriority {
		w("| %s | %d | %d | %d | %d | %d | %d | %d | %d | %d | %.1f %% |\n", s.Priority, s.Pairs, s.Compliant, s.VerifiedLate, s.Overdue, s.Pending, s.Failed, s.Offline, s.Exception, s.NotApplicable, s.PctOnTime)
	}
	w("\n---\n\n")

	// §6
	w("## 6. Evidence register and export manifest\n\nEvery export should include an evidence index. The evidence files themselves may be included in a ZIP package or provided through a controlled repository link, subject to the auditor’s access permissions.\n\n")
	w("| Evidence ID | Evidence item | Source system | Period / timestamp | Scope | Integrity hash | Confidentiality class | Included / link |\n|---|---|---|---|---|---|---|---|\n")
	for _, e := range pk.EvidenceRegister {
		inc := e.Included
		if !e.Complete {
			inc += " (incomplete: no records)"
		}
		w("| %s | %s | %s | %s | %s | `%s` | %s | %s |\n", e.ID, e.Item, cell(e.SourceSystem), cell(e.Period), cell(fmt.Sprintf("%s; %d records", e.Scope, e.Records)), e.SHA256, cell(e.Confidentiality), cell(inc))
	}
	w("\n### Export integrity and handling\n\nThe exported package should contain:\n\n")
	w("- This report in PDF and/or Markdown/CSV as requested by the organization.\n- A machine-readable summary (JSON or CSV) of findings, control statuses, and metrics.\n- An evidence index with object IDs, timestamps, source system, and hashes.\n- Report-generation timestamp, reporting period, filters, and product version.\n- A signed export manifest or verifiable digital signature where supported.\n- Redaction and access controls for sensitive hostnames, IP addresses, user IDs, vulnerability details, and infrastructure topology.\n\n")
	w("This package: `report.md` (this report), `summary.json` (machine-readable summary), `evidence/*.csv`, `manifest.json` (SHA-256 of every file, period, generation time, filters, product version) and `manifest.sig` (Ed25519 signature of manifest.json with the server's audit-signing key). Redacted: %v.\n\n", m.Redacted)
	w("The report should state whether evidence is sampled or population-wide and disclose omitted records, unsupported platforms, stale agents, and data-collection gaps.\n\n")
	for _, l := range pk.ScopeLimitations.Auto {
		w("- %s\n", l)
	}
	w("\n---\n\n")

	// §7
	w("## 7. Findings and corrective action plan\n\n| Finding ID | Control / source | Observation and evidence | Risk / impact | Severity | Root cause | Corrective action | Owner | Due date | Status |\n|---|---|---|---|---|---|---|---|---|---|\n")
	if len(pk.Findings) == 0 {
		w("| — | — | No findings. | — | — | — | — | — | — | — |\n")
	}
	for _, f := range pk.Findings {
		obs := f.Observation + " Evidence: " + strings.Join(f.EvidenceIDs, ", ") + "."
		if len(f.Affected) > 0 {
			obs += " Affected (sample): " + strings.Join(f.Affected, ", ") + "."
		}
		w("| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", f.ID, cell(f.Source), cell(obs), cell(f.Risk), f.Severity, cell(f.RootCause), cell(f.CorrectiveAction), cell(f.Owner), f.DueDate, f.Status)
	}
	w("\n### Risk acceptance / exception register\n\n| Exception ID | Endpoint/system scope | Patch / vulnerability | Reason patch is not applied | Compensating controls | Risk owner / approver | Opened | Expiry / review date | Status |\n|---|---|---|---|---|---|---|---|---|\n")
	if len(pk.Exceptions) == 0 {
		w("| — | — | — | No exceptions. | — | — | — | — | — |\n")
	}
	for _, x := range pk.Exceptions {
		w("| %s | %s | %s | %s | %s | %s | %s | %s | %s |\n", x.ExceptionID, cell(x.Scope), cell(x.Patch), cell(x.Reason), cell(x.CompensatingControls), cell(x.Owner+" / "+x.Approver), x.Opened, x.Expires, x.Status)
	}
	w("\n---\n\n")

	// §8
	w("## 8. Auditor review and sign-off\n\n| Role | Name | Conclusion / comments | Date |\n|---|---|---|---|\n")
	for _, s := range pk.Signoff {
		cm := s.Comments
		if cm == "" {
			cm = templateSignoffComment[s.Role]
			if cm == "" {
				cm = "Comments"
			}
			cm = "[" + cm + "]"
		}
		name, date := s.Name, s.Date
		if name == "" {
			name = "[Name]"
		}
		if date == "" {
			date = "[Date]"
		}
		w("| %s | %s | %s | %s |\n", cell(s.Role), cell(name), cell(cm), cell(date))
	}
	lim := pk.ScopeLimitations.Profile
	if lim == "" {
		lim = "See the disclosures in section 6."
	}
	w("\n**Scope limitations:** %s\n\n", strings.TrimSpace(lim))
	mr := pk.ManagementResponse
	if mr == "" {
		mr = "[Response and target dates.]"
	}
	w("**Management response:** %s\n\n---\n\n", mr)

	// §9
	w("## 9. Official references for mapping maintenance\n\nThese sources were consulted to prepare the candidate mapping. Compliance owners should check the official source for amendments and applicability before each reporting cycle.\n\n")
	for _, r := range pk.References {
		note := ""
		if r.Note != "" {
			note = " — " + r.Note
		}
		w("%d. %s, [%s](%s)%s\n", r.N, r.Label, r.Title, r.URL, map[bool]string{true: note, false: "."}[note != ""])
	}
	w("\n---\n\n*%s %s · report %s · generated %s · audit chain %s (%d events) · profile version %d (sha256 %s)*\n",
		Product, m.ProductVersion, m.ReportID, m.GeneratedAt, map[bool]string{true: "verified", false: "FAILED verification"}[pk.AuditChain.OK], pk.AuditChain.Events, pk.ProfileVersion.Version, shortHash(pk.ProfileVersion.SHA256))
	return b.String()
}

func clockLabel(c string) string {
	switch c {
	case "acquired":
		return "date the update was acquired (received in the isolated zone)"
	case "approved":
		return "date the update was approved for deployment"
	}
	return "vendor release date"
}

func dedupe(xs []string) []string {
	if len(xs) < 2 {
		return xs
	}
	// "critical: X", "high: X" → "X" when identical after the prefix.
	strip := func(s string) string {
		if i := strings.Index(s, ": "); i >= 0 {
			return s[i+2:]
		}
		return s
	}
	same := true
	for _, x := range xs[1:] {
		if strip(x) != strip(xs[0]) {
			same = false
		}
	}
	if same {
		return []string{strip(xs[0])}
	}
	return xs
}

func shortHash(h string) string {
	if len(h) > 12 {
		return h[:12]
	}
	return h
}
