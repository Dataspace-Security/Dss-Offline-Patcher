// title block and the Important note, then sections 1–9.

// StatusTone colours a control / assessment status.
func StatusTone(status string) pdf.Tone {
	s := strings.ToLower(status)
	switch {
	case strings.HasPrefix(s, "compliant"):
		return pdf.ToneGreen
	case strings.HasPrefix(s, "partially"):
		return pdf.ToneAmber
	case strings.HasPrefix(s, "non-compliant"), strings.HasPrefix(s, "non compliant"):
		return pdf.ToneRed
	case strings.HasPrefix(s, "not applicable"):
		return pdf.ToneGrey
	}
	return pdf.ToneBlue // not assessed / needs review
}

// SeverityTone colours a finding severity.
func SeverityTone(sev string) pdf.Tone {
	switch strings.ToLower(sev) {
	case "critical":
		return pdf.ToneRed
	case "high":
		return pdf.ToneAmber
	case "medium":
		return pdf.ToneBlue
	}
	return pdf.ToneGrey
}

func dash(s string) string {
	if strings.TrimSpace(s) == "" {
		return "—"
	}
	return s
}

// PDFFileName is the download name: DSS-Patcher-<report>-<period>-<id>.pdf.
func PDFFileName(report, period, id string) string {
	clean := func(s string) string {
		return strings.Map(func(r rune) rune {
			if r >= 'a' && r <= 'z' || r >= 'A' && r <= 'Z' || r >= '0' && r <= '9' || r == '-' || r == '_' || r == '.' {
				return r
			}
			return '-'
		}, s)
	}
	return "DSS-Patcher-" + clean(report) + "-" + clean(period) + "-" + clean(id) + ".pdf"
}

// FileName is this report's PDF download name.
func (pk *Pack) FileName() string {
	name := PDFFileName("compliance-report", pk.Meta.Period.From+"_"+pk.Meta.Period.To, pk.Meta.ReportID)
	if pk.Meta.Redacted {
		name = strings.TrimSuffix(name, ".pdf") + "-redacted.pdf"
	}
	return name
}

// Cover draws the DSS Patcher logo and wordmark at the top of the page.
func Cover(d *pdf.Doc, kicker string) {
	y := d.Y()
	w := d.Logo(pdf.MarginLeft, y, 46, pdf.Navy)
	x := pdf.MarginLeft + w + 12
	d.Text(x, y+24, pdf.Helvetica, 20, pdf.Navy, "DSS")
	d.Text(x+pdf.TextWidth(pdf.Helvetica, 20, "DSS "), y+24, pdf.HelveticaBold, 20, pdf.Navy, "Patcher")
	d.Text(x, y+40, pdf.Helvetica, 9, pdf.Grey, kicker)
	d.SetY(y + 66)
}

