// Build computes the pack. With in.Redact, salt keys the pseudonyms
// (store.PseudonymSalt). The input is not modified.
func Build(src *Input, salt []byte) (*Pack, error) {
	dup := *src
	in := &dup
	if in.Loc == nil {
		in.Loc = time.UTC
	}
	if in.Redact {
		in = redactInput(in, salt)
	}
	if in.Filters == nil {
		in.Filters = map[string]string{}
	}
	asOf := in.Now
	if in.To.Before(asOf) {
		asOf = in.To.Add(-time.Nanosecond)
	}
	gen := in.Now.In(in.Loc).Format(time.RFC3339)
	last := in.To.Add(-24 * time.Hour)
	sum := sha256.Sum256([]byte(in.From.Format("2006-01-02") + "|" + last.Format("2006-01-02") + "|" + gen))
	prof := in.Profile.Profile
	pk := &Pack{in: in, Disclaimer: Disclaimer, Profile: prof, ManagementResponse: prof.ManagementResponse, References: References,
		ProfileVersion: ProfileRef{Version: in.Profile.Version, EditedBy: in.Profile.EditedBy, EditedAt: in.Profile.EditedAt, SHA256: in.Profile.SHA256, IsDefault: in.Profile.IsDefault},
		AuditChain:     AuditChain{OK: in.Chain.OK, Events: in.Chain.Count, FirstBadSeq: in.Chain.FirstBadSeq, Error: in.Chain.Error, HeadSeq: in.AuditHeadSeq}}
	pk.Meta = Meta{ReportID: "CR-" + strings.ToUpper(hex.EncodeToString(sum[:])[:12]), Title: Title, Product: Product, ProductVersion: in.ProductVersion,
		GeneratedAt: gen, GeneratedBy: in.GeneratedBy, Filters: in.Filters, Redacted: in.Redact,
		Period:     Period{From: in.From.Format("2006-01-02"), To: last.Format("2006-01-02"), AsOf: asOf.In(in.Loc).Format(time.RFC3339), Timezone: in.Loc.String()},
		ReportType: "Auditor export", ControlDomain: "Endpoint and server patch management", CoverageModel: "Common controls with regulator-specific mappings",
		DocumentStatus:       "Generated by " + Product + " from dated evidence; conclusions are not final until reviewed and signed off (section 8)",
		RegulatoryReviewDate: mappingReviewDate(prof), PreparedFor: preparedFor(prof.LegalEntity)}

	res := buildPairs(in, asOf)
	pk.pairs = res.pairs
	f := pk.collectFacts(asOf, res)
	pk.Scope = pk.scope()
	pk.Timeliness = pk.timeliness(asOf, res)
	pk.Controls = pk.controls(f, res)
	pk.Findings = pk.findings(f, res)
	pk.Exceptions = pk.exceptionRows()
	pk.RegulatoryMappings = mappings(prof)
	pk.Signoff = signoff(prof)

	es := ExecutiveSummary{InScopeEndpoints: f.inScope, PendingRestart: f.pendingRestart, ActiveExceptions: len(f.activeExc),
		EmergencyOpenPastTarget: len(f.emergencyOpen), FindingsBySeverity: map[string]int{"critical": 0, "high": 0, "medium": 0, "low": 0}}
	cp := func(n int) CountPct { return CountPct{Count: n, Pct: pctOf(n, f.inScope)} }
	es.CurrentInventory, es.StaleInventory = cp(f.inScope-f.stale), cp(f.stale)
	es.CompliantWithPolicy, es.Overdue = cp(f.compliantEPs), cp(f.overdueEPs)
	for _, fd := range pk.Findings {
		es.FindingsBySeverity[strings.ToLower(fd.Severity)]++
	}
	pk.ExecutiveSummary = es

	reg, err := pk.register()
	if err != nil {
		return nil, err
	}
	pk.EvidenceRegister = reg
	complete := 0
	for _, e := range reg {
		if e.Complete {
			complete++
		}
	}
	pk.ExecutiveSummary.EvidenceCompletenessPct = pctOf(complete, len(reg))
	pk.ScopeLimitations = ScopeLimitations{Auto: pk.limitations(res), Profile: prof.ScopeLimitations}
	pk.OverallAssessment = pk.assess()
	pk.KeyFindings = pk.Findings
	if len(pk.KeyFindings) > 3 {
		pk.KeyFindings = pk.KeyFindings[:3]
	}
	return pk, nil
}

func mappingReviewDate(prof store.ReportProfile) string {
	latest := ""
	for _, m := range prof.RegulatoryMappings {
		if m.ReviewedAt > latest {
			latest = m.ReviewedAt
		}
	}
	if latest == "" {
		return MappingBaselineDate + " (template baseline; not reviewed for this entity)"
	}
	return latest
}

func (pk *Pack) scope() Scope {
	in := pk.in
	s := Scope{OSFamilies: []string{}, ApplicationVendors: []string{}, Sites: []string{}, Groups: []string{}}
	os, sites, groups, vendors := map[string]int{}, map[string]bool{}, map[string]bool{}, map[string]bool{}
	for _, e := range in.Endpoints {
		if e.RetiredAt != "" || e.Status == "retired" {
			s.RetiredExcluded++
			continue
		}
		s.EndpointsTotal++
		name := strings.TrimSpace(e.OS)
		if name == "" {
			name = "unknown"
		}
		if e.Build > 0 {
			name = fmt.Sprintf("%s build %d", name, e.Build)
		}
		os[name]++
		if e.Site != "" {
			sites[e.Site] = true
		}
		for _, g := range e.Groups {
			groups[g] = true
		}
	}
	for _, p := range in.Packages {
		if p.Vendor != "" {
			vendors[p.Vendor] = true
		}
	}
	for k, n := range os {
		s.OSFamilies = append(s.OSFamilies, fmt.Sprintf("%s (%d)", k, n))
	}
	for k := range sites {
		s.Sites = append(s.Sites, k)
	}
	for k := range groups {
		s.Groups = append(s.Groups, k)
	}
	for k := range vendors {
		s.ApplicationVendors = append(s.ApplicationVendors, k)
	}
	for _, xs := range [][]string{s.OSFamilies, s.Sites, s.Groups, s.ApplicationVendors} {
		sort.Strings(xs)
	}
	return s
}

// mappings: candidate rows until reviewed; the conclusion never says more
// than the reviewer recorded.
func mappings(prof store.ReportProfile) []Mapping {
	out := []Mapping{}
	for _, m := range prof.RegulatoryMappings {
		r := Mapping{RegulatoryMapping: m}
		if m.Applicable == "unknown" || m.Reviewer == "" {
			r.NeedsReview = true
			r.Conclusion = NotAssessedReview
		} else {
			parts := []string{"Applicable: " + m.Applicable + "."}
			if m.Rationale != "" {
				parts = append(parts, m.Rationale)
			}
			if m.ClauseRef != "" {
				parts = append(parts, "Clause: "+m.ClauseRef+".")
			}
			parts = append(parts, "Reviewed by "+m.Reviewer+" on "+orDash(m.ReviewedAt)+".")
			res := m.Result
			if res == "" {
				res = store.StatusNotAssessed
				if m.Applicable == "no" {
					res = store.StatusNotApplicable
				}
			}
			parts = append(parts, "Result: "+res+".")
			r.Conclusion = strings.Join(parts, " ")
		}
		out = append(out, r)
	}
	return out
}

func signoff(prof store.ReportProfile) []store.Signoff {
	out := make([]store.Signoff, 0, len(prof.Signoff))
	out = append(out, prof.Signoff...)
	return out
}

// assess suggests the overall assessment; the profile may override it.
func (pk *Pack) assess() Assessment {
	counts := map[string]int{}
	for _, c := range pk.Controls {
		counts[c.Status]++
	}
	es := pk.ExecutiveSummary
	crit := es.FindingsBySeverity["critical"]
	var st, why string
	switch {
	case es.InScopeEndpoints == 0:
		st, why = store.StatusNotAssessed, "No in-scope endpoints are enrolled."
	case counts[store.StatusNonCompliant] > 0 || crit > 0:
		st = store.StatusNonCompliant
		why = fmt.Sprintf("%d controls are non-compliant and %d critical findings are open.", counts[store.StatusNonCompliant], crit)
	case counts[store.StatusNotAssessed]*2 > len(pk.Controls):
		st = store.StatusNotAssessed
		why = fmt.Sprintf("%d of %d controls could not be assessed from the available evidence.", counts[store.StatusNotAssessed], len(pk.Controls))
	case counts[store.StatusCompliant]+counts[store.StatusNotApplicable] == len(pk.Controls) && es.FindingsBySeverity["high"] == 0 && es.FindingsBySeverity["medium"] == 0:
		st, why = store.StatusCompliant, "Every control operated as required for the tested scope and period."
	default:
		st = store.StatusPartial
		why = fmt.Sprintf("Controls exist, but %d are partially compliant and %d not assessed.", counts[store.StatusPartial], counts[store.StatusNotAssessed])
	}
	why = fmt.Sprintf("%s Endpoints compliant with the patch policy: %d of %d (%.1f %%); overdue: %d; without current inventory: %d; active exceptions: %d (reported separately, not counted as patched). Findings: %d critical, %d high, %d medium, %d low. Evidence completeness %.0f %%. A high patch percentage alone does not establish compliance; regulatory applicability needs the compliance review in section 4.",
		why, es.CompliantWithPolicy.Count, es.InScopeEndpoints, es.CompliantWithPolicy.Pct, es.Overdue.Count, es.StaleInventory.Count, es.ActiveExceptions,
		crit, es.FindingsBySeverity["high"], es.FindingsBySeverity["medium"], es.FindingsBySeverity["low"], es.EvidenceCompletenessPct)
	a := Assessment{Status: st, Rationale: why, Source: "computed", Suggested: st, SuggestedRationale: why}
	if o := pk.in.Profile.Profile.OverallAssessment; o.Status != "" {
		a.Status, a.Source = o.Status, "profile"
		a.Rationale = strings.TrimSpace(o.Rationale)
		if a.Rationale == "" {
			a.Rationale = "Set by the reviewer in the report profile."
		}
	}
	return a
}

// limitations discloses gaps (template §6: omitted records, unsupported
// platforms, stale agents, data-collection gaps).
func (pk *Pack) limitations(res pairsResult) []string {
	in := pk.in
	var out []string
	out = append(out, "Population-wide: every in-scope endpoint and every applicable endpoint/update pair is evaluated; nothing is sampled.")
	if pk.ExecutiveSummary.StaleInventory.Count > 0 {
		out = append(out, fmt.Sprintf("%d endpoints have no current inventory (stale, offline or not yet reporting); they are classified stale/offline, never compliant.", pk.ExecutiveSummary.StaleInventory.Count))
	}
	if in.To.After(in.Now) {
		out = append(out, "The period has not ended: state is evaluated at the generation time.")
	} else if in.Now.Sub(in.To) > 24*time.Hour {
		out = append(out, "Endpoint status (stale/offline, pending restart, support status) is the state at generation time; deadlines and verification times are evaluated at the end of the period.")
	}
	if res.noClock > 0 {
		out = append(out, fmt.Sprintf("%d endpoint/update pairs have no deadline because their clock start (release, acquisition or approval date) is unknown; they are reported as pending.", res.noClock))
	}
	if res.excluded > 0 {
		out = append(out, fmt.Sprintf("%d rejected, revoked or purged catalog packages are not required and are excluded from the timeliness calculation.", res.excluded))
	}
	missingIntel := 0
	for _, e := range in.Endpoints {
		if e.RetiredAt == "" && e.Missing != nil && e.Missing.OS+e.Missing.Apps > 0 {
			missingIntel++
		}
	}
	if missingIntel > 0 {
		out = append(out, fmt.Sprintf("%d endpoints lack updates reported by the update intelligence that are not yet in the catalog; their deadlines are evaluated only once the updates are acquired.", missingIntel))
	}
	if in.IntelAge == nil {
		out = append(out, "No update intelligence is loaded: operating-system support status and updates not yet acquired cannot be determined (PM-17).")
	}
	out = append(out, "Application end-of-life, vulnerability scan results, asset criticality rationale and network egress enforcement are not recorded by the product; they rely on the referenced evidence.")
	if in.PrivilegedTruncated {
		out = append(out, "The privileged audit event list is truncated; the complete trail is in the signed off-box audit export.")
	}
	if in.Settings.DeploymentMode == "single-server" {
		out = append(out, SingleServerLimitation)
	}
	if !in.Settings.AuditExportDir {
		out = append(out, "Audit events are held only in the server database (no signed off-box export configured).")
	}
	if len(pk.Profile.Exclusions) > 0 {
		var xs []string
		for _, x := range pk.Profile.Exclusions {
			xs = append(xs, fmt.Sprintf("%s (%s; approved by %s; review %s)", x.System, x.Reason, orDash(x.ApprovedBy), orDash(x.ReviewDate)))
		}
		out = append(out, "Excluded systems (from the profile, not enrolled): "+strings.Join(xs, "; ")+".")
	}
	if in.Redact {
		out = append(out, "Hostnames, endpoint IDs, IP addresses and user IDs are replaced with stable pseudonyms; the mapping is held by the organisation.")
	}
	unreviewed := 0
	for _, m := range pk.RegulatoryMappings {
		if m.NeedsReview {
			unreviewed++
		}
	}
	if unreviewed > 0 {
		out = append(out, fmt.Sprintf("%d regulatory mapping rows are candidate mappings that have not been reviewed for this entity.", unreviewed))
	}
	return out
}

func preparedFor(entity string) string {
	if strings.TrimSpace(entity) == "" {
		return "Organization / legal entity not recorded (set it in the report profile)"
	}
	return entity
}
