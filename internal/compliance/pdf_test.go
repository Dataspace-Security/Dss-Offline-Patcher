// report.pdf: a valid PDF with the template's cover and sections 1–9 in
// order, inside the signed package (listed in the manifest, so
// verify-report covers it), byte-identical to Pack.PDF.
func TestReportPDF(t *testing.T) {
	pk := build(t, fixture())
	b, err := pk.PDF()
	if err != nil {
		t.Fatal(err)
	}
	if _, err := pdf.Check(b); err != nil {
		t.Fatal(err)
	}
	pages, err := pdf.PageTexts(b)
	if err != nil {
		t.Fatal(err)
	}
	if len(pages) < 6 {
		t.Fatalf("pages: %d", len(pages))
	}
	cover := strings.Join(pages[0], " ")
	for _, want := range []string{"DSS", "Patcher", Title, "Important:", pk.Meta.ReportID, "Report type", "Generated by"} {
		if !strings.Contains(cover, want) {
			t.Errorf("cover lacks %q", want)
		}
	}
	var all []string
	for _, p := range pages {
		all = append(all, p...)
	}
	idx := func(s string) int {
		for i, x := range all {
			if x == s {
				return i
			}
		}
		return -1
	}
	prev := -1
	for _, h := range []string{"1. Executive summary", "Overall assessment", "Key findings", "2. Scope and methodology", "2.1 Organization and regulatory profile",
		"2.2 Offline update-delivery model", "2.3 Assessment method", "2.4 Status values", "3. Common patch management control matrix",
		"4. India regulatory mapping", "4.1 Regulatory mapping fields required in the product", "5. Patch timeliness and compliance calculation",
		"5.1 Policy-defined deadlines", "5.2 Calculation rules", "6. Evidence register and export manifest", "7. Findings and corrective action plan",
		"Risk acceptance / exception register", "8. Auditor review and sign-off", "9. Official references for mapping maintenance"} {
		i := idx(h)
		if i < 0 {
			t.Errorf("heading %q missing", h)
			continue
		}
		if i < prev {
			t.Errorf("heading %q out of order", h)
		}
		prev = i
	}
	for i, p := range pages {
		if !strings.HasPrefix(p[len(p)-1], "DSS Patcher · "+pk.Meta.ReportID+" · page ") {
			t.Errorf("page %d footer: %q", i+1, p[len(p)-1])
		}
	}
	// The control matrix spans pages: its header is on each of them.
	pageOf := func(h string) int {
		for i, p := range pages {
			for _, s := range p {
				if s == h {
					return i
				}
			}
		}
		return -1
	}
	from, to := pageOf("3. Common patch management control matrix"), pageOf("4. India regulatory mapping")
	if from < 0 || to <= from {
		t.Fatalf("control matrix pages %d..%d", from, to)
	}
	for i := from; i <= to; i++ {
		rows := 0
		for _, s := range pages[i] {
			if s == "4. India regulatory mapping" {
				break
			}
			if len(s) == 5 && strings.HasPrefix(s, "PM-") {
				rows++
			}
		}
		if rows > 0 && !strings.Contains(strings.Join(pages[i], "|"), "Control ID|Control objective|Auditor evidence / product data") {
			t.Errorf("page %d has controls but no table header", i+1)
		}
	}

	pub, priv, _ := ed25519.GenerateKey(nil)
	var buf bytes.Buffer
	m, err := pk.WriteZip(&buf, priv, nil)
	if err != nil {
		t.Fatal(err)
	}
	listed := false
	for _, f := range m.Files {
		listed = listed || f.Path == "report.pdf"
	}
	if !listed {
		t.Fatal("report.pdf not in the manifest")
	}
	if _, err := VerifyZip(buf.Bytes(), pub); err != nil {
		t.Fatal(err)
	}
	zr, _ := zip.NewReader(bytes.NewReader(buf.Bytes()), int64(buf.Len()))
	var out bytes.Buffer
	zw := zip.NewWriter(&out)
	for _, f := range zr.File {
		rc, _ := f.Open()
		body, _ := io.ReadAll(rc)
		rc.Close()
		if f.Name == "report.pdf" {
			if !bytes.Equal(body, b) {
				t.Error("report.pdf in the package differs from Pack.PDF")
			}
			body = bytes.Replace(body, []byte("/Title"), []byte("/Titlf"), 1)
		}
		w, _ := zw.Create(f.Name)
		w.Write(body)
	}
	zw.Close()
	if _, err := VerifyZip(out.Bytes(), pub); err == nil || !strings.Contains(err.Error(), "report.pdf") {
		t.Fatalf("tampered report.pdf verified: %v", err)
	}

	// OFFPATCH_PDF_SAMPLE=<path>: keep a copy for people to open.
	if p := os.Getenv("OFFPATCH_PDF_SAMPLE"); p != "" {
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, b, 0o644); err != nil {
			t.Fatal(err)
		}
	}
}

func TestPDFFileName(t *testing.T) {
	if got := PDFFileName("compliance-report", "2026-10-01_2026-10-18", "CR-ABC"); got != "DSS-Patcher-compliance-report-2026-10-01_2026-10-18-CR-ABC.pdf" {
		t.Fatal(got)
	}
	if got := PDFFileName("audit log", "a/b", "x\"y"); got != "DSS-Patcher-audit-log-a-b-x-y.pdf" {
		t.Fatal(got)
	}
}
