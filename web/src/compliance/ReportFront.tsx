// Cover block and sections 1–4 of the auditor report.
import type { ReactNode } from "react";
import { BrandMark } from "../components/icons";
import type { CompliancePack, Control, Finding, PackMapping } from "./types";
import { templateRowFor } from "./normalize";
import { fmtCountPct, fmtDate, fmtPct, fmtStamp, StatusBadge, Txt } from "./format";
import {
  APPLICABILITY_NOTE_1, APPLICABILITY_NOTE_2, APPLICABILITY_NOTE_BOLD, ASSESSMENT_RATIONALE_NOTE, CONTROL_MATRIX_INTRO, CONTROLS,
  COVER_FIELDS, IMPORTANT_DISCLAIMER, MAPPING_FIELDS, MAPPING_FIELDS_INTRO, MAPPING_FIELDS_OUTRO, METHOD_INTRO, METHOD_STEPS,
  mappingTitle, NOT_ASSESSED_REVIEW, OFFLINE_MODEL_INTRO, OFFLINE_MODEL_LABELS, REPORT_TITLE, STATUS_DEFINITIONS, TELEMETRY_NOTE,
} from "./templateText";

export function Section({ n, title, children }: { n: number; title: string; children: ReactNode }) {
  return (
    <section className="crep-sec" aria-labelledby={`crep-s${n}`}>
      <h2 id={`crep-s${n}`} className="crep-h2"><span className="crep-h2-num">{n}.</span> {title}</h2>
      {children}
    </section>
  );
}

export function EvidenceIds({ ids }: { ids: string[] }) {
  if (ids.length === 0) return null;
  return <div className="crep-cell-ids">Evidence: {ids.map((id) => <span key={id} className="crep-mono crep-chip">{id}</span>)}</div>;
}

export function Cover({ pack }: { pack: CompliancePack }) {
  const { meta, profile } = pack;
  const by = [meta.generated_by.user, meta.generated_by.role].filter(Boolean).join(" / ");
  const fromServer: Record<string, string> = {
    "Report type": meta.report_type, "Control domain": meta.control_domain, "Coverage model": meta.coverage_model,
    "Document status": meta.document_status, "Regulatory review date": meta.regulatory_review_date,
  };
  const pv = pack.profile_version;
  const rows: [string, ReactNode][] = [
    ...COVER_FIELDS.map(([k, v]) => [k, fromServer[k] || v] as [string, ReactNode]),
    ["Prepared for", <Txt v={meta.prepared_for || profile.legal_entity} placeholder="Organization / legal entity not set in the report profile" />],
    ["Reporting period", <>{fmtDate(meta.period.from) || "—"} to {fmtDate(meta.period.to) || "—"}{meta.period.timezone ? ` (${meta.period.timezone})` : ""}</>],
    ["Report ID", <span className="crep-mono">{meta.report_id || "—"}</span>],
    ["Generated at", <Txt v={fmtStamp(meta.generated_at)} />],
    ["Generated by", <Txt v={by} />],
    ["Product version", <Txt v={meta.product_version ? `DSS Patcher ${meta.product_version}` : ""} />],
    ["Report profile", pv.is_default || !pv.version
      ? <span className="crep-empty">Defaults (the report profile has not been saved)</span>
      : <>Version {pv.version}, saved {fmtStamp(pv.edited_at) || "—"} by {pv.edited_by.replace(/^user:/, "") || "—"}</>],
  ];
  if (meta.redacted) rows.push(["Redaction", "Hostnames, IP addresses and user IDs are replaced with stable pseudonyms."]);
  return (
    <header className="crep-cover">
      <div className="crep-cover-brand">
        <BrandMark size={44} className="crep-cover-mark" />
        <div>
          <div className="crep-cover-product">DSS <b>Patcher</b></div>
          <div className="crep-cover-tag">Offline patch management</div>
        </div>
      </div>
      <h1 className="crep-title">{meta.title || REPORT_TITLE}</h1>
      <div className="crep-cover-entity">{profile.legal_entity || meta.prepared_for || "Organization / legal entity not set"}</div>
      <table className="crep-table crep-kv">
        <tbody>
          {rows.map(([k, v]) => (
            <tr key={k}><th scope="row">{k}</th><td>{v}</td></tr>
          ))}
        </tbody>
      </table>
      <aside className="crep-important" role="note">
        <b>Important:</b> {pack.disclaimer || IMPORTANT_DISCLAIMER}
      </aside>
    </header>
  );
}

function KeyFinding({ f }: { f: Finding }) {
  const sample = f.affected.slice(0, 5).join(", ");
  const affected = f.affected_count
    ? `${f.affected_count}${sample ? ` (${sample}${f.affected_count > 5 ? ", …" : ""})` : ""}`
    : sample;
  return (
    <li>
      {f.id && <span className="crep-mono">{f.id} </span>}<b>{f.title || f.observation}</b>
      {f.severity && <> · {f.severity}</>}
      {f.risk && <> — Impact: {f.risk}</>}
      {affected && <>; Affected systems: {affected}</>}
      {f.owner && <>; Owner: {f.owner}</>}
      {f.due_date && <>; Due: {fmtDate(f.due_date) || f.due_date}</>}
    </li>
  );
}

export function ExecutiveSummarySection({ pack }: { pack: CompliancePack }) {
  const s = pack.executive_summary;
  const f = s.findings_by_severity;
  const rows: [string, string][] = [
    ["In-scope endpoints", String(s.in_scope_endpoints)],
    ["Endpoints with current inventory", fmtCountPct(s.current_inventory)],
    ["Endpoints compliant with applicable patch policy", fmtCountPct(s.compliant_with_policy)],
    ["Endpoints overdue for one or more required patches", fmtCountPct(s.overdue)],
    ["Endpoints with stale inventory", fmtCountPct(s.stale_inventory)],
    ["Endpoints pending restart", String(s.pending_restart)],
    ["Approved patch exceptions still active", String(s.active_exceptions)],
    ["Emergency patches open past target", String(s.emergency_open_past_target)],
    ["Control findings: critical / high / medium / low", `${f.critical} / ${f.high} / ${f.medium} / ${f.low}`],
    ["Evidence completeness", fmtPct(s.evidence_completeness_pct)],
  ];
  const oa = pack.overall_assessment;
  const overridden = oa.source === "profile";
  return (
    <Section n={1} title="Executive summary">
      <table className="crep-table crep-measures">
        <thead><tr><th>Measure</th><th className="num">Result</th></tr></thead>
        <tbody>{rows.map(([k, v]) => <tr key={k}><td>{k}</td><td className="num">{v}</td></tr>)}</tbody>
      </table>

      <h3 className="crep-h3">Overall assessment</h3>
      <div className="crep-assessment">
        <StatusBadge status={oa.status} large />
        <span className="crep-assessment-src">
          {overridden ? "Set by the organization in the report profile" : "Computed from product evidence; to be confirmed by the reviewer"}
        </span>
      </div>
      <p><b>Assessment rationale:</b> {oa.rationale || <span className="crep-empty">No rationale recorded.</span>}</p>
      {overridden && oa.suggested && (
        <p className="crep-cell-muted">
          Product-computed suggestion: <StatusBadge status={oa.suggested} />{oa.suggested_rationale ? ` ${oa.suggested_rationale}` : ""}
        </p>
      )}
      <p className="crep-note">{ASSESSMENT_RATIONALE_NOTE}</p>

      <h3 className="crep-h3">Key findings</h3>
      {pack.key_findings.length === 0 ? <p className="crep-empty">No findings were generated for this period.</p> : (
        <ol className="crep-list">{pack.key_findings.map((k, i) => <KeyFinding key={k.id || i} f={k} />)}</ol>
      )}
    </Section>
  );
}

export function ScopeSection({ pack }: { pack: CompliancePack }) {
  const p = pack.profile;
  const sc = pack.scope;
  const exclusions = p.exclusions.length === 0 ? <span className="crep-empty">None recorded</span> : (
    <ul className="crep-list crep-list-tight">
      {p.exclusions.map((e, i) => (
        <li key={i}><b>{e.system || "—"}</b>: {e.reason || "no reason recorded"}; approved by {e.approved_by || "—"}; review {fmtDate(e.review_date) || "—"}</li>
      ))}
    </ul>
  );
  const osFamilies = [...sc.os_families, ...sc.application_vendors.map((v) => `${v} (applications)`)];
  const productScope = [
    `${sc.endpoints_total} enrolled endpoint${sc.endpoints_total === 1 ? "" : "s"}`,
    sc.retired_excluded ? `${sc.retired_excluded} retired (excluded)` : "",
    sc.sites.length ? `sites: ${sc.sites.join(", ")}` : "",
    sc.groups.length ? `groups: ${sc.groups.join(", ")}` : "",
  ].filter(Boolean).join("; ");
  const rows: [string, ReactNode][] = [
    ["Legal entity", <Txt v={p.legal_entity} />],
    ["Business / regulated activity", <Txt v={p.regulated_activity} />],
    ["Applicable regulator(s)", <Txt v={p.regulators.join(", ")} />],
    ["Entity category / size category where relevant", <Txt v={p.entity_category} />],
    ["Assessment owner", <Txt v={p.assessment_owner} />],
    ["Independent reviewer", <Txt v={p.independent_reviewer} />],
    ["Systems in scope", <><Txt v={p.systems_in_scope} /><div className="crep-cell-muted">Product inventory: {productScope}</div></>],
    ["Endpoint types in scope", <Txt v={p.endpoint_types} />],
    ["Operating systems / application families", osFamilies.length ? osFamilies.join("; ") : <span className="crep-empty">No inventory reported</span>],
    ["Exclusions", exclusions],
  ];
  return (
    <Section n={2} title="Scope and methodology">
      <h3 className="crep-h3">2.1 Organization and regulatory profile</h3>
      <table className="crep-table crep-kv">
        <thead><tr><th>Attribute</th><th>Value</th></tr></thead>
        <tbody>{rows.map(([k, v]) => <tr key={k}><th scope="row">{k}</th><td>{v}</td></tr>)}</tbody>
      </table>

      <h3 className="crep-h3">2.2 Offline update-delivery model</h3>
      <p>{OFFLINE_MODEL_INTRO}</p>
      <ul className="crep-list">
        {OFFLINE_MODEL_LABELS.map(([key, label]) => (
          <li key={key}><b>{label}:</b> <Txt v={p.offline_model[key]} placeholder="Not described in the report profile" /></li>
        ))}
      </ul>

      <h3 className="crep-h3">2.3 Assessment method</h3>
      <p>{METHOD_INTRO}</p>
      <ol className="crep-list">{METHOD_STEPS.map((s) => <li key={s}>{s}</li>)}</ol>

      <h3 className="crep-h3">2.4 Status values</h3>
      <ul className="crep-list crep-status-defs">
        {STATUS_DEFINITIONS.map(([label, text]) => (
          <li key={label}><StatusBadge status={label} /> {text}</li>
        ))}
      </ul>
      <p className="crep-note">{TELEMETRY_NOTE}</p>
    </Section>
  );
}

const SOURCE_NOTE: Record<string, string> = { manual: "Manual assessment (report profile)", none: "No product evidence" };

function ControlRow({ def, c }: { def: (typeof CONTROLS)[number]; c?: Control }) {
  return (
    <tr>
      <td className="crep-mono nowrap"><b>{def.id}</b></td>
      <td>{c?.objective || def.objective}</td>
      <td>
        <div className="crep-cell-muted">{c?.auditor_evidence || def.evidence}</div>
        {c?.evidence && <div className="crep-cell-data"><b>Product data:</b> {c.evidence}</div>}
        {c && <EvidenceIds ids={c.evidence_ids} />}
      </td>
      <td>
        {c?.suggested_test || def.test}
        {c?.test_performed && <div className="crep-cell-data"><b>Test performed:</b> {c.test_performed}</div>}
      </td>
      <td>
        <StatusBadge status={c?.status} />
        {c && SOURCE_NOTE[c.source] && <div className="crep-cell-muted">{SOURCE_NOTE[c.source]}</div>}
        {c?.rationale && <div className="crep-cell-rationale">{c.rationale}</div>}
        {!c && <div className="crep-cell-rationale">No evidence returned for this control.</div>}
      </td>
    </tr>
  );
}

export function ControlMatrixSection({ pack }: { pack: CompliancePack }) {
  const byId = new Map(pack.controls.map((c) => [c.id.toUpperCase(), c]));
  const extra = pack.controls.filter((c) => !CONTROLS.some((d) => d.id === c.id.toUpperCase()));
  return (
    <Section n={3} title="Common patch management control matrix">
      <p>{CONTROL_MATRIX_INTRO}</p>
      <div className="crep-wide">
        <table className="crep-table crep-controls">
          <colgroup><col className="w-id" /><col className="w-obj" /><col className="w-ev" /><col className="w-test" /><col className="w-status" /></colgroup>
          <thead>
            <tr><th>Control ID</th><th>Control objective</th><th>Auditor evidence / product data</th><th>Suggested test</th><th>Status</th></tr>
          </thead>
          <tbody>
            {CONTROLS.map((d) => <ControlRow key={d.id} def={d} c={byId.get(d.id)} />)}
            {extra.map((c) => <ControlRow key={c.id} def={{ id: c.id, objective: c.objective, evidence: c.auditor_evidence, test: c.suggested_test }} c={c} />)}
          </tbody>
        </table>
      </div>
    </Section>
  );
}

function Conclusion({ m }: { m: PackMapping }) {
  const applicable = m.applicable === "yes" ? "Yes" : m.applicable === "no" ? "No" : "Unknown";
  const details = (
    <>
      {m.clause_ref && <div><b>Clause:</b> {m.clause_ref}</div>}
      {m.rationale && <div><b>Rationale:</b> {m.rationale}</div>}
      {(m.reviewer || m.reviewed_at) && <div className="crep-cell-muted">Reviewed by {m.reviewer || "—"}{m.reviewed_at ? `, ${fmtDate(m.reviewed_at) || m.reviewed_at}` : ""}</div>}
      {m.notes && <div className="crep-cell-muted">{m.notes}</div>}
    </>
  );
  if (m.needs_review) {
    return (
      <div className="crep-conclusion">
        <div className="crep-conclusion-na">{m.conclusion || NOT_ASSESSED_REVIEW}</div>
        {m.applicable !== "unknown" && <div className="crep-cell-muted">Applicable: {applicable}</div>}
        {details}
      </div>
    );
  }
  return (
    <div className="crep-conclusion">
      <div><b>Applicable:</b> {applicable}</div>
      {m.result && <div><b>Result:</b> <StatusBadge status={m.result} /></div>}
      {m.conclusion && m.conclusion !== m.result && <div>{m.conclusion}</div>}
      {details}
    </div>
  );
}

